import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

// Keep original artwork; serve smaller, reproducible WebP copies to visitors.
const sourceDirectory = new URL("../everydayimg/", import.meta.url);
const outputDirectory = new URL("../images/wallpapers/", import.meta.url);
const files = (await readdir(sourceDirectory))
  .filter((file) => /\.(jpe?g|png)$/i.test(file))
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));

await mkdir(outputDirectory, { recursive: true });
const wallpapers = [];

for (const file of files) {
  const filename = `${path.parse(file).name}.webp`;
  await sharp(fileURLToPath(new URL(file, sourceDirectory)))
    .rotate()
    .resize({ width: 1920, height: 1080, fit: "inside", withoutEnlargement: true })
    .webp({ quality: 78, effort: 6 })
    .toFile(fileURLToPath(new URL(filename, outputDirectory)));
  wallpapers.push(`images/wallpapers/${filename}`);
}

await writeFile(
  new URL("../wallpapers.js", import.meta.url),
  `// Generated by npm run build:images. Add original images to everydayimg/.\nexport const WALLPAPERS = ${JSON.stringify(wallpapers, null, 2)};\n`,
);
console.log(`Optimized ${wallpapers.length} wallpapers.`);
